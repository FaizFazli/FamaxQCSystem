--  NOTES
-- =====================================================================
--
-- NOTE 1 - the routings this will not cost cleanly, and why they are left alone.
--   * 92 distinct process names across 1,117 steps, and some of them are the same process:
--     SWISS AUTO LATHE / SWISS AUTO-LATHE / SWISS AUTO LATHE MACHINING / SWISS AUTO-LATHE
--     MACHINING; POLISH and POLISHING; TURN MILL and TURNMILL. The trim and case-fold above
--     collapse whitespace and capitals, nothing more - these are four different strings and each
--     needs its own cost on each part that uses it. Merging them is a decision about the shop,
--     not about a database, and it belongs in the part master where the routings are edited.
--   * "faiz test again" appears on 4 routing steps and "v4_TEST" is a job order part. Test data
--     in the master, costable like anything else, not this file's business to delete.
--   * 55 of the 898 JobOrder rows have no resolvable part number because Part_Name nests brackets
--     inside brackets. They appear in v_joborder_wip_cost with a null part_no and no costs, which
--     is the honest answer; naming them would need somebody to say which part each one is.
--
-- NOTE 2 - what the RLS grant costs.
--   Anyone holding the anon key (it ships in assets/app-config.js) can read and write these
--   tables directly, bypassing the page - including the cost figures. That is already true of
--   Parts, JobOrder, SalesOrders and the tooling and gauge tables; this makes costing consistent
--   with them rather than introducing anything new. If cost should be held to a higher standard
--   than the rest of the app, the fix is a real Supabase Auth session and these policies revert
--   to `to authenticated`.
--
-- NOTE 3 - verify:
--   select count(*) from v_part_process_cost;                          -- 1117
--   select count(*) from v_part_cost_summary;                          -- 235
--   select count(*) from v_part_cost_summary where fully_costed;       -- 0, until costs are entered
--   select count(*) from v_joborder_wip_cost;                          -- 210
--   select count(*) from v_joborder_wip_cost where not all_done;       -- 50
--   select count(*) from v_joborder_wip_cost where part_no is null;    -- 17 (the nested-bracket names:
--                                                                     --     55 rows, 9 spellings, 17 job/part units)
--   select sum(wip_value) from v_joborder_wip_cost where not all_done; -- 0, until costs are entered
--   -- the trim and case-fold actually hold:
--   insert into process_cost (part_no, process_name, cost_per_pcs) values ('  TESTPN ', ' harden ', 1);
--   insert into process_cost (part_no, process_name, cost_per_pcs) values ('TESTPN', 'HARDEN', 2);
--                                                                      -- second one fails, 23505
--   select part_no, process_name from process_cost where part_no = 'TESTPN';   -- TESTPN | harden
--   select action, old_cost_per_pcs, new_cost_per_pcs from process_cost_history
--    where part_no = 'TESTPN';                                         -- INSERT | null | 1.0000
--   delete from process_cost where part_no = 'TESTPN';                 -- leaves the DELETE row behind
